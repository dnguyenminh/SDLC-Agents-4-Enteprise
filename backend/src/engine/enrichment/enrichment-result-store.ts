/**
 * SA4E-107: Enrichment result persistence (extracted from CodeEnrichmentHandler).
 * Stores summary, pseudo code, tags and provenance metadata on the symbols
 * table (last-write-wins, BR-07).
 */

import type { Logger } from 'pino';
import type { DatabaseAdapter } from '../../database/adapters/DatabaseAdapter.js';
import type { CodeEnrichmentLLMResponse, EnrichmentStrategy } from './types.js';
import { validateTags } from './tag-validator.js';

/** Max pseudo code length (BR-05). */
const MAX_PSEUDO_CODE_LENGTH = 2000;

/** Persist enrichment results to symbols table (last-write-wins, BR-07). */
export async function storeEnrichmentResults(
  adapter: DatabaseAdapter,
  logger: Logger,
  symbolId: number,
  response: CodeEnrichmentLLMResponse,
  strategy: EnrichmentStrategy,
): Promise<void> {
  const tags = validateTags(response.tags);
  const tagsJson = tags.length > 0 ? JSON.stringify(tags) : null;
  const pseudoCode = truncatePseudoCode(response.pseudo_code, strategy);
  const now = new Date().toISOString();

  // Write pseudo_code directly (not COALESCE): on re-enrichment the fresh LLM
  // output must overwrite stale/incorrect values instead of being preserved.
  await adapter.runAsync(
    `UPDATE symbols SET summary = ?, pseudo_code = ?,
     llm_tags = ?, enrichment_status = 'COMPLETED', enriched_at = ? WHERE id = ?`,
    [response.summary, pseudoCode, tagsJson, now, symbolId],
  );
  await storeProvenanceMeta(adapter, logger, symbolId, strategy, pseudoCode, now);
}

/** Truncate pseudo code to MAX_PSEUDO_CODE_LENGTH (BR-05); none for TAG_EXTRACTION. */
function truncatePseudoCode(raw: string | undefined, strategy: EnrichmentStrategy): string | null {
  // Store pseudo_code for all summarizing strategies (CLASS, FUNCTION, PEGA).
  // Only TAG_EXTRACTION produces no pseudo code.
  if (strategy === 'TAG_EXTRACTION' || !raw) return null;
  return raw.length > MAX_PSEUDO_CODE_LENGTH
    ? raw.slice(0, MAX_PSEUDO_CODE_LENGTH) + '...'
    : raw;
}

/** S5: Store provenance metadata in enrichment_meta (best-effort, non-fatal). */
async function storeProvenanceMeta(
  adapter: DatabaseAdapter,
  logger: Logger,
  symbolId: number,
  strategy: EnrichmentStrategy,
  pseudoCode: string | null,
  now: string,
): Promise<void> {
  // Generated by LLM, with provenance marker for re-entry safety
  const provenanceMeta = {
    generatedBy: 'llm',
    enrichedAt: now,
    strategy,
    pseudoCodeLength: pseudoCode?.length ?? 0,
  };
  try {
    await adapter.runAsync(
      `UPDATE symbols SET enrichment_meta = ? WHERE id = ?`,
      [JSON.stringify(provenanceMeta), symbolId],
    );
  } catch (err) {
    // Non-fatal: provenance tracking is best-effort
    logger.debug({ err, symbolId }, '[enrichment] Failed to write provenance meta');
  }
}
